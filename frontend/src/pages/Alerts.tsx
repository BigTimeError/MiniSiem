import {
  useCallback,
  useEffect,
  useState,
} from "react";
import { Link, useSearchParams } from "react-router-dom";

import Layout from "../components/Layout";
import {
  getAlerts,
  updateAlertStatus,
} from "../api/alerts";

import { useEventStream } from "../hooks/useEventStream";

import type {
  Alert,
  AlertStatus,
  Severity,
} from "../types/siem";

const PAGE_SIZE = 20;

const STATUSES: AlertStatus[] = [
  "open",
  "acknowledged",
  "resolved",
  "false_positive",
];

const SEVERITIES: Severity[] = [
  "info",
  "low",
  "medium",
  "high",
  "critical",
];

function Alerts() {
  const [searchParams, setSearchParams] =
    useSearchParams();

  const [alerts, setAlerts] = useState<Alert[]>([]);
  const [total, setTotal] = useState(0);
  const [page, setPage] = useState(0);

  const [status, setStatus] = useState<AlertStatus | "">(
    (searchParams.get("status") as AlertStatus | null) ?? "",
  );

  const [severity, setSeverity] = useState<Severity | "">(
    (searchParams.get("severity") as Severity | null) ?? "",
  );

  const [affectedHost, setAffectedHost] = useState(
    searchParams.get("affected_host") ?? "",
  );

  const [hostInput, setHostInput] = useState(
    searchParams.get("affected_host") ?? "",
  );

  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);

  const loadAlerts = useCallback(() => {
    setLoading(true);
    setError(null);

    getAlerts({
      limit: PAGE_SIZE,
      offset: page * PAGE_SIZE,
      status: status || undefined,
      severity: severity || undefined,
      affected_host: affectedHost || undefined,
    })
      .then((response) => {
        setAlerts(response.items);
        setTotal(response.total);
      })
      .catch((error) => {
        setError(
          error instanceof Error
            ? error.message
            : "Failed to load alerts.",
        );
      })
      .finally(() => {
        setLoading(false);
      });
  }, [page, status, severity, affectedHost]);

  useEffect(() => {
    loadAlerts();
  }, [loadAlerts]);

  useEventStream(
    useCallback(
      (streamEvent) => {
        if (streamEvent.type === "alert_created") {
          loadAlerts();
        }
      },
      [loadAlerts],
    ),
  );

  const totalPages = Math.ceil(total / PAGE_SIZE);

  function updateUrl(
    newStatus: AlertStatus | "",
    newSeverity: Severity | "",
    newAffectedHost: string,
  ) {
    const params = new URLSearchParams();

    if (newStatus) {
      params.set("status", newStatus);
    }

    if (newSeverity) {
      params.set("severity", newSeverity);
    }

    if (newAffectedHost.trim()) {
      params.set("affected_host", newAffectedHost.trim());
    }

    setSearchParams(params);
  }

  function handleStatusChange(value: AlertStatus | "") {
    setStatus(value);
    setPage(0);
    updateUrl(value, severity, affectedHost);
  }

  function handleSeverityChange(value: Severity | "") {
    setSeverity(value);
    setPage(0);
    updateUrl(status, value, affectedHost);
  }

  function applyHostFilter() {
    const value = hostInput.trim();

    setAffectedHost(value);
    setHostInput(value);
    setPage(0);
    updateUrl(status, severity, value);
  }

  function clearHostFilter() {
    setHostInput("");
    setAffectedHost("");
    setPage(0);
    updateUrl(status, severity, "");
  }

  function handleHostKeyDown(
    event: React.KeyboardEvent<HTMLInputElement>,
  ) {
    if (event.key === "Enter") {
      applyHostFilter();
    }
  }

  async function handleAlertStatusChange(
    alertId: number,
    newStatus: AlertStatus,
  ) {
    try {
      const updatedAlert = await updateAlertStatus(
        alertId,
        newStatus,
      );

      setAlerts((currentAlerts) =>
        currentAlerts.map((alert) =>
          alert.id === updatedAlert.id ? updatedAlert : alert,
        ),
      );
    } catch (error) {
      setError(
        error instanceof Error
          ? error.message
          : "Failed to update alert.",
      );
    }
  }

  return (
    <Layout>
      <div className="page">
        <header className="page-header">
          <div>
            <span className="dashboard-eyebrow">
              SECURITY MONITORING
            </span>
            <h1>Alerts</h1>
            <p>
              Review, investigate and manage security alerts
              generated by detection rules.
            </p>
          </div>

          <div className="page-live-status">
            <span className="status-dot" />
            Alert monitoring
          </div>
        </header>

        <section className="filter-card">
          <div
            className="section-header"
            style={{ padding: 0, marginBottom: "20px", borderBottom: "none" }}
          >
            <div>
              <h2>Filters</h2>
              <p>Narrow down alerts by status, severity or host.</p>
            </div>

            <span className="btn" style={{ cursor: "default", opacity: 0.8 }}>
              {total} {total === 1 ? "alert" : "alerts"}
            </span>
          </div>

          <div className="filter-grid">
            <div className="filter-group">
              <label htmlFor="alert-status">Status</label>
              <select
                id="alert-status"
                className="filter-select"
                value={status}
                onChange={(event) =>
                  handleStatusChange(
                    event.target.value as AlertStatus | "",
                  )
                }
              >
                <option value="">All statuses</option>
                {STATUSES.map((value) => (
                  <option key={value} value={value}>
                    {value.replace("_", " ")}
                  </option>
                ))}
              </select>
            </div>

            <div className="filter-group">
              <label htmlFor="alert-severity">Severity</label>
              <select
                id="alert-severity"
                className="filter-select"
                value={severity}
                onChange={(event) =>
                  handleSeverityChange(
                    event.target.value as Severity | "",
                  )
                }
              >
                <option value="">All severities</option>
                {SEVERITIES.map((value) => (
                  <option key={value} value={value}>
                    {value}
                  </option>
                ))}
              </select>
            </div>

            <div className="filter-group">
              <label htmlFor="affected-host">Affected host</label>

              <div className="filter-actions">
                <input
                  id="affected-host"
                  type="text"
                  className="filter-input"
                  placeholder="e.g. server01"
                  value={hostInput}
                  onChange={(event) =>
                    setHostInput(event.target.value)
                  }
                  onKeyDown={handleHostKeyDown}
                />

                <button
                  type="button"
                  className="btn btn-primary"
                  onClick={applyHostFilter}
                >
                  Apply
                </button>

                {affectedHost && (
                  <button
                    type="button"
                    className="btn"
                    onClick={clearHostFilter}
                  >
                    Clear
                  </button>
                )}
              </div>
            </div>
          </div>
        </section>

        {error && (
          <div className="error-state" role="alert">
            <div>
              <strong>Something went wrong</strong>
              <p style={{ margin: "4px 0 0", fontSize: "12px" }}>{error}</p>
            </div>

            <button type="button" className="btn" onClick={loadAlerts}>
              Retry
            </button>
          </div>
        )}

        {loading ? (
          <div className="state-card">
            <span className="status-dot" style={{ marginRight: "10px" }} />
            Loading alerts...
          </div>
        ) : !error ? (
          <section className="content-card">
            <div className="section-header">
              <div>
                <h2>All alerts</h2>
                <p>Review alert details and update their status.</p>
              </div>
              <span className="btn" style={{ cursor: "default", opacity: 0.8 }}>
                {total} total
              </span>
            </div>

            <div className="table-container">
              <table className="data-table">
                <thead>
                  <tr>
                    <th>Timestamp</th>
                    <th>Alert</th>
                    <th>Rule</th>
                    <th>Source IP</th>
                    <th>Severity</th>
                    <th>Status</th>
                    <th>Action</th>
                  </tr>
                </thead>

                <tbody>
                  {alerts.map((alert) => (
                    <tr key={alert.id}>
                      <td className="text-timestamp">
                        {new Date(
                          alert.timestamp,
                        ).toLocaleString()}
                      </td>

                      <td>
                        <Link
                          to={`/alerts/${alert.id}`}
                          className="text-link"
                          style={{ fontWeight: 500 }}
                        >
                          {alert.title}
                        </Link>
                      </td>

                      <td>
                        <span
                          className="text-mono"
                          style={{
                            fontSize: "11px",
                            padding: "3px 6px",
                            background: "#202531",
                            borderRadius: "4px",
                            border: "1px solid #2b3140",
                          }}
                        >
                          {alert.rule_id}
                        </span>
                      </td>

                      <td className="text-mono">
                        {alert.source_ip ?? "-"}
                      </td>

                      <td>
                        <span
                          className={`badge-severity severity-${alert.severity.toLowerCase()}`}
                        >
                          {alert.severity}
                        </span>
                      </td>

                      <td>
                        <span
                          className={`badge-status status-${alert.status}`}
                        >
                          {alert.status.replace("_", " ")}
                        </span>
                      </td>

                      <td>
                        <select
                          aria-label={`Update status for ${alert.title}`}
                          className="filter-select"
                          style={{
                            minWidth: "130px",
                            padding: "6px 8px",
                            fontSize: "11px",
                          }}
                          value={alert.status}
                          onChange={(event) =>
                            handleAlertStatusChange(
                              alert.id!,
                              event.target.value as AlertStatus,
                            )
                          }
                        >
                          {STATUSES.map((value) => (
                            <option key={value} value={value}>
                              {value.replace("_", " ")}
                            </option>
                          ))}
                        </select>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>

              {alerts.length === 0 && (
                <div className="empty-state">
                  <span className="empty-icon">✓</span>
                  <strong>No alerts found</strong>
                  <p
                    style={{
                      margin: 0,
                      color: "var(--text-subtle)",
                      fontSize: "12px",
                    }}
                  >
                    Try changing your filters or check back when
                    new alerts arrive.
                  </p>
                </div>
              )}
            </div>

            {totalPages > 1 && (
              <div className="pagination">
                <span>
                  Page {page + 1} of {totalPages}
                </span>

                <div className="pagination-buttons">
                  <button
                    disabled={page === 0}
                    onClick={() =>
                      setPage((current) => current - 1)
                    }
                  >
                    Previous
                  </button>

                  <button
                    disabled={page >= totalPages - 1}
                    onClick={() =>
                      setPage((current) => current + 1)
                    }
                  >
                    Next
                  </button>
                </div>
              </div>
            )}
          </section>
        ) : null}
      </div>
    </Layout>
  );
}

export default Alerts;